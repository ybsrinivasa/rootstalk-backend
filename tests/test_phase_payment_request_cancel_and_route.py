# ── C1: /farmer/my-subscriptions surfaces pending_payment_from richly ────

@requires_docker
@pytest.mark.asyncio
async def test_pending_payment_from_carries_phone_and_hours_remaining(db):
    _, _, farmer, delegate, sub = await _seed(db)

    await delegate_payment(
        subscription_id=sub.id,
        request=PaymentDelegateRequest(delegate_phone="+919900400099"),
        db=db, current_user=farmer,
    )
    subs = await my_subscriptions(db=db, current_user=farmer)
    pending = next(s for s in subs if s["id"] == sub.id)["pending_payment_from"]
    assert pending is not None
    assert pending["user_id"] == delegate.id
    assert pending["name"] == delegate.name
    assert pending["phone"] == delegate.phone
    assert "payment_request_id" in pending
    # 24h request just created — should be 23 or 24 hours remaining,
    # never negative.
    assert 22 <= pending["hours_remaining"] <= 24


# ── C6: /facilitator/payment-requests payload is decorated ────────────────

@requires_docker
@pytest.mark.asyncio
async def test_facilitator_payment_requests_is_decorated(db):
    client, pkg, farmer, delegate, sub = await _seed(db)

    await delegate_payment(
        subscription_id=sub.id,
        request=PaymentDelegateRequest(delegate_phone="+919900400099"),
        db=db, current_user=farmer,
    )

    out = await facilitator_payment_requests(db=db, current_user=delegate)
    assert len(out) == 1
    row = out[0]
    assert row["farmer_user_id"] == farmer.id
    assert row["farmer_name"] == farmer.name
    assert row["farmer_phone"] == farmer.phone
    assert row["package_id"] == pkg.id
    assert row["package_name"] == pkg.name
    assert row["amount"] == 199.0
    assert row["status"] == "PENDING"
    assert 22 <= row["hours_remaining"] <= 24


# ── C4: facilitator decline marks DECLINED + only the right row ───────────

@requires_docker
@pytest.mark.asyncio
async def test_facilitator_decline_flips_only_pending_row(db):
    _, _, farmer, delegate, sub = await _seed(db)

    await delegate_payment(
        subscription_id=sub.id,
        request=PaymentDelegateRequest(delegate_phone="+919900400099"),
        db=db, current_user=farmer,
    )
    pr_id = (await db.execute(
        select(SubscriptionPaymentRequest.id).where(
            SubscriptionPaymentRequest.subscription_id == sub.id,
        )
    )).scalar_one()

    out = await facilitator_decline_payment(
        request_id=pr_id, db=db, current_user=delegate,
    )
    assert out["status"] == "DECLINED"

    # Replaying the decline on the same (now-non-pending) row 404s.
    with pytest.raises(HTTPException) as ei:
        await facilitator_decline_payment(
            request_id=pr_id, db=db, current_user=delegate,
        )
    assert ei.value.status_code == 404
