async def _seed(db, *, delegate_phone="+919900400099"):
    """Make a farmer + delegate (Facilitator onboarded at the client) +
    WAITLISTED sub. The delegate is `register_promoter`-onboarded so
    `_assert_active_facilitator` passes when the test exercises
    /facilitator/* endpoints. The delegate's phone is fixed because
    `delegate_payment` looks up the user by phone; the farmer's
    phone is auto-generated by the factory."""
    sa = await make_user(db, name="SA")
    client = await make_client(db)
    pkg = await make_package(db, client)
    farmer = await make_user(db, name="Farmer")
    delegate = await make_self_registered_user(
        db, phone=delegate_phone, role="FACILITATOR", name="Delegate",
    )
    sub = await make_subscription(
        db, farmer=farmer, client=client, package=pkg,
    )
    sub.status = SubscriptionStatus.WAITLISTED   # factory hardcodes ACTIVE
    await db.commit()
    # Re-read so the in-memory enum membership matches what
    # /farmer/my-subscriptions will see (a String(20) column read
    # back as a plain str, not the SubscriptionStatus enum
    # instance the test set in Python).
    await db.refresh(sub)

    await register_promoter(
        client_id=client.id,
        request={"phone": delegate_phone, "promoter_type": "FACILITATOR"},
        db=db, current_user=sa,
    )
    return client, pkg, farmer, delegate, sub


# ── C8: double-delegation is rejected ─────────────────────────────────────

@requires_docker
@pytest.mark.asyncio
async def test_second_delegation_while_pending_returns_409(db):
    _, _, farmer, delegate, sub = await _seed(db)

    await delegate_payment(
        subscription_id=sub.id,
        request=PaymentDelegateRequest(delegate_phone="+919900400099"),
        db=db, current_user=farmer,
    )

    with pytest.raises(HTTPException) as ei:
        await delegate_payment(
            subscription_id=sub.id,
            request=PaymentDelegateRequest(delegate_phone="+919900400099"),
            db=db, current_user=farmer,
        )
    assert ei.value.status_code == 409
    assert ei.value.detail["code"] == "payment_request_already_pending"


# ── C2: farmer cancels → request flips to CANCELLED ───────────────────────

@requires_docker
@pytest.mark.asyncio
async def test_farmer_cancel_flips_pending_to_cancelled(db):
    _, _, farmer, _, sub = await _seed(db)

    await delegate_payment(
        subscription_id=sub.id,
        request=PaymentDelegateRequest(delegate_phone="+919900400099"),
        db=db, current_user=farmer,
    )
    await cancel_delegation(
        subscription_id=sub.id, db=db, current_user=farmer,
    )

    pr = (await db.execute(
        select(SubscriptionPaymentRequest).where(
            SubscriptionPaymentRequest.subscription_id == sub.id,
        )
    )).scalar_one()
    assert pr.status == "CANCELLED"


